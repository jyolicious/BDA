"""Spark Aggregation Engine for Host-Level Behavioral Profiling."""
from pyspark.sql import DataFrame
from pyspark.sql.functions import avg, col, count, countDistinct, round, sum, when
from src.common.logger import get_logger

logger = get_logger("spark_aggregation")


def aggregate_by_source_ip(df: DataFrame) -> DataFrame:
    """Compute behavioral aggregations per source IP for network analytics.

    Calculates:
    - event_count: Total events generated by host
    - total_bytes_sent: Volume of data transmitted
    - total_bytes_received: Volume of data received
    - avg_packet_count: Average packets per flow
    - unique_dest_ports: Number of distinct destination ports probed
    - failed_conn_count: Number of dropped, timed-out, or rejected flows
    - avg_duration_ms: Mean flow connection duration
    - protocol_diversity: Number of distinct transport protocols utilized
    """
    logger.info("Computing Spark distributed behavioral aggregations per source IP...")

    is_failed = when(col("connection_status").isin("FAILED", "REJECTED", "TIMEOUT"), 1).otherwise(0)

    agg = df.groupBy("source_ip").agg(
        count("*").alias("event_count"),
        sum("bytes_sent").alias("total_bytes_sent"),
        sum("bytes_received").alias("total_bytes_received"),
        round(avg("packet_count"), 2).alias("avg_packet_count"),
        countDistinct("destination_port").alias("unique_dest_ports"),
        sum(is_failed).alias("failed_conn_count"),
        round(avg("duration_ms"), 2).alias("avg_duration_ms"),
        countDistinct("protocol").alias("protocol_diversity")
    )

    # Derive additional analytical ratios
    agg = (
        agg
        .withColumn("bytes_per_event", round(col("total_bytes_sent") / col("event_count"), 2))
        .withColumn("failed_ratio", round(col("failed_conn_count") / col("event_count"), 4))
    )

    count_ips = agg.count()
    logger.info(f"Aggregated statistics computed for {count_ips:,} unique source IPs.")
    return agg
